import PropTypes from "prop-types";
import { FontAwesomeIcon } from "@fortawesome/react-fontawesome";
import { faCopy } from "@fortawesome/free-solid-svg-icons";
import { useLocale } from "@/contexts/LocaleContext";
import { Button, Card, Field, Input, Select } from "@/shared/ui";

const PROJECT_TYPES = [
  ["residential", "projects.residential"],
  ["commercial", "projects.commercial"],
  ["industrial", "projects.industrial"],
  ["mixed_use", "projects.mixedUse"],
];

const MEASUREMENT_UNITS = [
  ["m2", "projects.squareMeters"],
  ["ft2", "projects.squareFeet"],
  ["vara2", "projects.squareVaras"],
];

function ProjectForm({
  formId,
  mode = "create",
  values,
  onChange,
  onSubmit,
  onMeasurementUnitChange,
  onCopyGuid,
  currency,
  lotCountLocked = false,
}) {
  const { t } = useLocale();
  const isEdit = mode === "edit";
  const requireContactFields = mode === "create";
  const setField = (field) => (event) => onChange(field, event.target.value);

  const handleMeasurementUnitChange = (event) => {
    const next = event.target.value;
    if (onMeasurementUnitChange) onMeasurementUnitChange(next);
    else onChange("measurement_unit", next);
  };

  return (
    <form id={formId} onSubmit={onSubmit} className="space-y-4">
      <Card title={t("projects.formInfo")}>
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <div className="sm:col-span-2">
            <Field label={t("projects.name")} required>
              <Input
                value={values.name}
                onChange={setField("name")}
                placeholder={t("projects.enterProjectName")}
                autoComplete="off"
                required
              />
            </Field>
          </div>

          <Field label={t("projects.code")}>
            <Input
              value={values.code}
              onChange={setField("code")}
              placeholder={t("projects.enterCode")}
              autoComplete="off"
            />
          </Field>

          <div className="relative">
            <Field label={t("projects.guid")}>
              <Input
                value={values.guid}
                readOnly
                placeholder={t("projects.guidAutoGenerated")}
                className={`font-mono text-micro ${
                  isEdit ? "" : "bg-surface-2 text-ink-3"
                }`}
              />
            </Field>
            {isEdit && values.guid && onCopyGuid && (
              <Button
                variant="ghost"
                size="sm"
                onClick={onCopyGuid}
                title={t("common.copy")}
                className="absolute bottom-1 right-1 px-2"
              >
                <FontAwesomeIcon icon={faCopy} aria-hidden="true" />
              </Button>
            )}
          </div>
        </div>
      </Card>

      <Card title={t("projects.formPricing")}>
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <Field label={t("projects.pricePerUnit")} required>
            <Input
              type="number"
              min="0"
              step="0.01"
              value={values.price_per_square_unit}
              onChange={setField("price_per_square_unit")}
              required
            />
          </Field>

          <Field label={t("projects.currency")}>
            <Input
              value={currency}
              readOnly
              disabled
              className="bg-surface-2 text-ink-3"
            />
          </Field>

          <Field
            label={t("projects.lotsCount")}
            required
            hint={
              lotCountLocked
                ? t("projects.lotsCountDisabledWhenReserved")
                : undefined
            }
          >
            <Input
              type="number"
              min="0"
              step="1"
              value={values.lot_count}
              onChange={setField("lot_count")}
              required
              disabled={lotCountLocked}
              className={lotCountLocked ? "bg-surface-2 text-ink-3" : ""}
            />
          </Field>

          <Field label={t("projects.interestRate")} required>
            <Input
              type="number"
              min="0"
              step="0.01"
              value={values.interest_rate}
              onChange={setField("interest_rate")}
              required
            />
          </Field>

          <div className="grid grid-cols-1 gap-4 sm:col-span-2 sm:grid-cols-3">
            <Field label={t("projects.commissionRateDirect")} required>
              <Input
                type="number"
                min="0"
                step="0.01"
                value={values.commission_rate_direct}
                onChange={setField("commission_rate_direct")}
                required
              />
            </Field>

            <Field label={t("projects.commissionRateBank")} required>
              <Input
                type="number"
                min="0"
                step="0.01"
                value={values.commission_rate_bank}
                onChange={setField("commission_rate_bank")}
                required
              />
            </Field>

            <Field label={t("projects.commissionRateCash")} required>
              <Input
                type="number"
                min="0"
                step="0.01"
                value={values.commission_rate_cash}
                onChange={setField("commission_rate_cash")}
                required
              />
            </Field>
          </div>
        </div>
      </Card>

      <Card title={t("projects.formLocation")}>
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <div className="sm:col-span-2">
            <Field
              label={t("projects.address")}
              required={requireContactFields}
            >
              <Input
                value={values.address}
                onChange={setField("address")}
                placeholder={t("projects.enterAddress")}
                autoComplete="street-address"
                required={requireContactFields}
              />
            </Field>
          </div>

          <Field label={t("projects.city")}>
            <Input
              value={values.city}
              onChange={setField("city")}
              placeholder={t("projects.enterCity")}
              autoComplete="address-level2"
            />
          </Field>

          <Field label={t("projects.projectType")}>
            <Select
              value={values.project_type}
              onChange={setField("project_type")}
            >
              {PROJECT_TYPES.map(([value, key]) => (
                <option key={value} value={value}>
                  {t(key)}
                </option>
              ))}
            </Select>
          </Field>

          <Field label={t("projects.deliveryDate")}>
            <Input
              type="date"
              value={values.delivery_date}
              onChange={setField("delivery_date")}
            />
          </Field>

          <Field label={t("projects.measurementUnit")}>
            <Select
              value={values.measurement_unit}
              onChange={handleMeasurementUnitChange}
            >
              {MEASUREMENT_UNITS.map(([value, key]) => (
                <option key={value} value={value}>
                  {t(key)}
                </option>
              ))}
            </Select>
          </Field>
        </div>
      </Card>

      <Card title={t("projects.description")}>
        <Field required={requireContactFields}>
          <textarea
            value={values.description}
            onChange={setField("description")}
            rows={4}
            aria-label={t("projects.description")}
            placeholder={t("projects.enterDescription")}
            required={requireContactFields}
            className="min-h-28 w-full rounded-control border border-line-strong bg-surface px-3 py-2 text-[16px] text-ink outline-none sm:text-body-lg"
          />
        </Field>
      </Card>
    </form>
  );
}

ProjectForm.propTypes = {
  formId: PropTypes.string.isRequired,
  mode: PropTypes.oneOf(["create", "edit"]),
  values: PropTypes.shape({
    name: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    guid: PropTypes.string,
    code: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    description: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    address: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    city: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    lot_count: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    price_per_square_unit: PropTypes.oneOfType([
      PropTypes.string,
      PropTypes.number,
    ]),
    measurement_unit: PropTypes.string,
    interest_rate: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    commission_rate_direct: PropTypes.oneOfType([
      PropTypes.string,
      PropTypes.number,
    ]),
    commission_rate_bank: PropTypes.oneOfType([
      PropTypes.string,
      PropTypes.number,
    ]),
    commission_rate_cash: PropTypes.oneOfType([
      PropTypes.string,
      PropTypes.number,
    ]),
    delivery_date: PropTypes.string,
    project_type: PropTypes.string,
  }).isRequired,
  onChange: PropTypes.func.isRequired,
  onSubmit: PropTypes.func.isRequired,
  onMeasurementUnitChange: PropTypes.func,
  onCopyGuid: PropTypes.func,
  currency: PropTypes.string,
  lotCountLocked: PropTypes.bool,
};

export default ProjectForm;
